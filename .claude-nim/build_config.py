"""Write config.yaml from what actually answered a completion.

The old config was hand-maintained, which is how it ended up listing models
that 404 for this account and aliases with empty fallback lists. This script
takes probe_results.json (models that returned a real completion) and emits:

  * the five Claude Code aliases, pointed at the strongest available models
  * every callable NVIDIA model, under its exact catalog id
  * a fallback chain for every group, strongest first
  * a pass-through group so an unlisted raw id still reaches NVIDIA

Nothing is written to config.yaml directly: the result goes to
config.yaml.new, is validated, and only then replaces the live file.
"""
from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "config.yaml.new")
# Non-NVIDIA chat models (DeepSeek, GLM, ...) live in the same NIM catalog but
# were missing from probe_results.json because an early probe used a short
# timeout and counted a reasoning-only answer as a failure. probe_extra.py
# re-probes them with a long timeout; only a model that produced text *and* a
# tool call is admitted here.
EXTRA_PROBE = os.path.join(HERE, "probe_extra.json")

# Models that answer completions but must never be used as a general
# fallback: they are classifiers/translators, not assistants.
SPECIALIST = {
    "nvidia/nemotron-3.5-content-safety",
    "nvidia/llama-3.1-nemotron-safety-guard-8b-v3",
    "nvidia/riva-translate-4b-instruct-v2",
}

# Preference order for the general assistant chain. Anything that answered but
# is not named here is appended after these, so a newly deployed model still
# becomes available without editing this list.
PREFERRED = [
    "nvidia/nemotron-3-ultra-550b-a55b",
    "nvidia/nemotron-3.5-super-vl-120b-a12b",
    "stepfun-ai/step-5-preview",
    "meta/muse-glimmer-30b",
    "z-ai/glm-5.3",
    "z-ai/glm-5.3-flash",
    "openai/gpt-oss-20b",
    "deepseek-ai/deepseek-v4.1-flash",
    "nvidia/nemotron-3-nano-omni-30b-a3b-reasoning",
    "nvidia/nemotron-3.5-lightning-30b-a3b",
    "poolside/laguna-xs-2.1",
    "nvidia/ising-calibration-1.5-31b",
    "meta/llama-3.2-11b-vision-instruct",
]

# Claude Code's tier aliases -> the model that should back each one.
# `claude-mythos-*` is the name the client itself uses for the flagship tier;
# it is listed alongside the fable aliases so both resolve to the same model
# instead of falling through the unknown-model path.
ALIASES = {
    "claude-fable-5.1": "nvidia/nemotron-3-ultra-550b-a55b",
    "claude-fable-5": "nvidia/nemotron-3-ultra-550b-a55b",
    "claude-mythos-5.1": "nvidia/nemotron-3-ultra-550b-a55b",
    "claude-mythos-5": "nvidia/nemotron-3-ultra-550b-a55b",
    "claude-opus-5.5": "nvidia/nemotron-3-ultra-550b-a55b",
    "claude-sonnet-5.5": "nvidia/nemotron-3.5-super-vl-120b-a12b",
    "claude-haiku-5.5": "nvidia/nemotron-3.5-lightning-30b-a3b",
}


def rank(models: list[str]) -> list[str]:
    general = [m for m in models if m not in SPECIALIST]
    ordered = [m for m in PREFERRED if m in general]
    ordered += [m for m in general if m not in ordered]
    return ordered


def main() -> int:
    with open(os.path.join(HERE, "probe_results.json"), encoding="utf-8") as handle:
        working = [entry["id"] for entry in json.load(handle)["works"]]

    if os.path.exists(EXTRA_PROBE):
        try:
            with open(EXTRA_PROBE, encoding="utf-8") as handle:
                extra = json.load(handle)
        except (OSError, ValueError):
            extra = {}
        for model, entry in extra.items():
            if not isinstance(entry, dict) or not entry.get("content"):
                continue
            tools = entry.get("tools") or {}
            if tools.get("status") == 200 and (tools.get("calls") or 0) >= 1:
                if model not in working:
                    working.append(model)

    chat = rank(working)
    if not chat:
        print("no working models; refusing to write a config", file=sys.stderr)
        return 1

    specialists = [m for m in working if m in SPECIALIST]
    chain = chat + specialists

    def fallbacks_for(name: str) -> list[str]:
        if name in SPECIALIST:
            return []
        return [m for m in chain if m != name][:4]

    lines: list[str] = []
    add = lines.append

    add("# Claude Code proxy - generated by build_config.py")
    add("#")
    add("# Sources: probe_results.json (models that returned a real completion")
    add("# against this account's key) and the alias map in build_config.py.")
    add("# Regenerate with:  python build_config.py && python config-guard.py")
    add("#")
    add(f"# Callable chat models: {len(chat)} general, {len(specialists)} specialist.")
    add("#")
    add("# Do not hand-edit a fallback list into `[]`: LiteLLM accepts that, and it")
    add("# silently disables failover, so one 429 ends the turn. config-guard.py")
    add("# rejects that shape, and start-proxy.ps1 restores config.good.yaml if it")
    add("# ever appears again.")
    add("")
    add("general_settings:")
    add('  master_key: os.environ/LITELLM_MASTER_KEY')
    add("  allow_requests_on_db_unavailable: true")
    add("  disable_spend_logs: true")
    add("  disable_reset_budget: true")
    add("")
    add("litellm_settings:")
    add("  drop_params: true")
    add("  request_timeout: 600")
    add("  # Two quick retries, then move to the next model in the chain: Claude")
    add("  # Code retries independently, and a model that is throttled stays")
    add("  # throttled seconds later.")
    add("  num_retries: 2")
    add("  retry_after: 2")
    add("  allowed_fails: 2")
    add("  cooldown_time: 20")
    add("  set_verbose: false")
    add("  turn_off_message_logging: true")
    add("  fallbacks:")

    for alias, target in ALIASES.items():
        # The alias itself may point at a model that is not callable; fall back
        # to whatever ranked first.
        primary = target if target in chat else chat[0]
        rest = [m for m in chat if m != primary][:3]
        rendered = ", ".join(f'"{m}"' for m in rest)
        add(f'    - "{alias}": [{rendered}]')

    for model in chain:
        rest = fallbacks_for(model)
        if not rest:
            # Specialist endpoints have no sensible stand-in. A fallback entry
            # with an empty list is exactly the shape config-guard rejects, so
            # leave them out of the map entirely.
            continue
        rendered = ", ".join(f'"{m}"' for m in rest)
        add(f'    - "{model}": [{rendered}]')

    add('    - "nvidia/*": ' + "[" + ", ".join(f'"{m}"' for m in chat[:3]) + "]")
    add("")
    add("router_settings:")
    add("  routing_strategy: simple-shuffle")
    add("  num_retries: 2")
    add("  retry_after: 2")
    add("  allowed_fails: 2")
    add("  cooldown_time: 20")
    add("  enable_pre_call_checks: false")
    add("  retry_policy:")
    add("    RateLimitErrorRetries: 2")
    add("    InternalServerErrorRetries: 2")
    add("    TimeoutErrorRetries: 2")
    add("    AuthenticationErrorRetries: 0")
    add("    BadRequestErrorRetries: 0")
    add("")
    add("model_list:")
    add("  # ---- Claude Code tier aliases ----")

    for alias, target in ALIASES.items():
        primary = target if target in chat else chat[0]
        add(f"  - model_name: {alias}")
        add("    litellm_params:")
        add(f"      model: nvidia_nim/{primary}")
        add("      api_key: os.environ/NVIDIA_API_KEY")

    add("")
    add("  # ---- NVIDIA models verified callable for this account ----")
    for model in chat:
        add(f"  - model_name: {model}")
        add("    litellm_params:")
        add(f"      model: nvidia_nim/{model}")
        add("      api_key: os.environ/NVIDIA_API_KEY")

    if specialists:
        add("")
        add("  # ---- Specialist endpoints (classification / translation) ----")
        for model in specialists:
            add(f"  - model_name: {model}")
            add("    litellm_params:")
            add(f"      model: nvidia_nim/{model}")
            add("      api_key: os.environ/NVIDIA_API_KEY")

    add("")
    add("  # ---- Pass-through for any raw catalog id not listed above ----")
    add('  - model_name: "nvidia/*"')
    add("    litellm_params:")
    add('      model: "nvidia_nim/nvidia/*"')
    add("      api_key: os.environ/NVIDIA_API_KEY")
    add("")

    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))

    print(f"wrote {OUT}: {len(chat) + len(specialists)} models, {len(ALIASES)} aliases")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
